#!/usr/bin/env python3
r"""Recover a .proto schema from smali classes generated by protobuf-javalite.

protobuf-javalite keeps no descriptors, but each message's
`dynamicMethod(BUILD_MESSAGE_INFO)` holds a RawMessageInfo string (field numbers, types,
required/optional/repeated) and an object table (field names, sub-message classes, enum
verifiers). The script reads them from .smali and prints a pseudo-.proto. This is how on 18-21.09.2026 the
protocol of the WSA "Shell" channel was recovered (device/microsoft/wsa_x86_64/WsaShellBridge/proto/, docs/protocol.md).

    java -cp tools/baksmali-2.5.2.jar:tools/dexlib2-2.5.2.jar:tools/guava-31.1-jre.jar:tools/jcommander-1.82.jar:tools/util-2.5.2.jar \
        org.jf.baksmali.Main disassemble classesN.dex -o smaliN
    bin/proto-from-smali.py smaliN/com/microsoft/windows/redirection/Shell\$*.smali

Info string format (protobuf-java, GeneratedMessageLite/RawMessageInfo): each character is a number;
header: flags, fieldCount, [oneofCount, hasBitsCount, minField, maxField, entries, maps,
repeated, checkInit]; then per field: fieldNumber, fieldType[, hasBitIndex | oneofIndex].
Types 0..17 — scalars/message/enum (optional, required if bit 0x100), 18..48 — repeated
(35..48 packed), 50 — map, 51.. — oneof. Enums are printed by verifier class name.
Numbers >= 0xD800 (surrogates) did not occur in these schemas — not handled.
"""
import os
import re
import sys

TYPES = ['double', 'float', 'int64', 'uint64', 'int32', 'fixed64', 'fixed32', 'bool', 'string',
         'message', 'bytes', 'uint32', 'enum', 'sfixed32', 'sfixed64', 'sint32', 'sint64', 'group']


def decode_type(t):
    base = t & 0xFF
    flags = t & ~0xFF
    if base < 18:
        return TYPES[base], ('required' if flags & 0x100 else 'optional'), flags
    if base < 50:
        r = base - 18
        if r < 17:
            return TYPES[r], 'repeated', flags
        return 'packed_' + TYPES[r - 17], 'repeated', flags
    if base == 50:
        return 'map', 'map', flags
    return TYPES[base - 51], 'oneof', flags


def unescape(s):
    s = s.replace('\\t', '\t').replace('\\n', '\n').replace('\\r', '\r')
    return re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), s)


def parse(src):
    m = re.search(r'\.method protected final dynamicMethod.*?\.end method', src, re.S)
    if not m:
        return None
    body = m.group(0)
    # only the BUILD_MESSAGE_INFO branch: from new-array to newMessageInfo
    mi = re.search(r'new-array.*?newMessageInfo', body, re.S)
    sub = mi.group(0) if mi else body
    strings = re.findall(r'const-string(?:/jumbo)? v\d+, "((?:[^"\\]|\\.)*)"', sub)
    info, objs = None, []
    for s in strings:
        u = unescape(s)
        if u and ord(u[0]) < 32 and len(u) > 5:
            info = u
        else:
            objs.append(u)
    return (info, objs) if info else None


def decode(info):
    it = iter(info)
    nxt = lambda: ord(next(it))
    flags, field_count = nxt(), nxt()
    if field_count == 0:
        return dict(proto2=flags & 1, oneofs=0, fields=[])
    oneofs, has_bits = nxt(), nxt()
    for _ in range(6):
        nxt()  # minField, maxField, entries, maps, repeated, checkInit
    fields = []
    for _ in range(field_count):
        fn, ft = nxt(), nxt()
        base = ft & 0xFF
        if base >= 51 or (has_bits > 0 and base < 18):
            nxt()  # oneof index / has-bit index
        fields.append((fn, ft))
    return dict(proto2=flags & 1, oneofs=oneofs, fields=fields)


def type_from_getter(src, name, label):
    getter = 'get' + name[0].upper() + name[1:]
    sig = r'\(I\)' if label == 'repeated' else r'\(\)'
    m = re.search(r'\.method public ' + re.escape(getter) + sig + r'(L[^;]+;)', src)
    return m.group(1).split('/')[-1].rstrip(';').replace('$', '.') if m else None


def main(paths):
    for p in sorted(paths):
        src = open(p).read()
        r = parse(src)
        if not r:
            continue
        info, objs = r
        d = decode(info)
        cls = os.path.basename(p)[:-6]
        print('message %s {   // %s, proto%s' % (cls.split('$')[-1], cls, '2' if d['proto2'] else '3'))
        oi = 1 if d['proto2'] and objs and objs[0].startswith('bitField') else 0
        oi += d['oneofs'] * 2  # oneof names + their case fields
        for fn, ft in d['fields']:
            tname, label, fl = decode_type(ft)
            name = objs[oi].rstrip('_') if oi < len(objs) else '?'
            oi += 1
            typ = tname
            if tname in ('message', 'group', 'enum'):
                typ = type_from_getter(src, name, label) or (tname + '?')
            note = ' [utf8]' if fl & 0x200 else ''
            print('  %s %s %s = %d;%s' % (label, typ, name, fn, note))
        print('}')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
