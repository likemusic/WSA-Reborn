#!/usr/bin/env bash
# Extract the ARM translator (libhoudini) from the WSA reference into the build tree as proprietary blobs —
# so that the tree build itself puts it into system_ext (with proper inodes and labels), and into system —
# links to it (modules in device/microsoft/wsa_x86_64/houdini/Android.bp).
#
#   bin/extract-houdini-blobs.sh <tree root> [--wsa-vendor <reference vendor>] [--wsa-system <reference system>]
#
# Creates <tree>/device/microsoft/wsa-houdini/: proprietary/system_ext/... (file copies),
# houdini.mk (PRODUCT_COPY_FILES + link modules) and Android.bp (libhoudini.so itself, both bitnesses). device.mk includes it via
# inherit-product-if-exists; BoardConfig.mk, when it is present, allows ELF in PRODUCT_COPY_FILES.
# Without the directory the build goes without ARM translation, as before. This directory is not committed to git:
# Intel/Microsoft binaries (BYOB). By default the reference is $WSA_REF.
#
# The layout and why it is this way — bin/add-houdini.sh (same result for already-built images).
set -euo pipefail
. "$(dirname "$0")/wsa-env.sh"

TREE="${1:?build tree root (or any dir that will later be moved into the tree)}"; shift
WSA_VENDOR="$WSA_REF/vendor"
WSA_SYSTEM="$WSA_REF/system/system"
while [ $# -gt 0 ]; do
    case "$1" in
        --wsa-vendor) WSA_VENDOR="$2"; shift 2 ;;
        --wsa-system) WSA_SYSTEM="$2"; shift 2 ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done
for f in lib64/libhoudini.so lib/libhoudini.so lib64/arm64/libtcb.so lib/arm/libtcb.so; do
    [ -r "$WSA_VENDOR/$f" ] || { echo "reference vendor lacks $f" >&2; exit 1; }
done
for f in bin/houdini bin/houdini64; do
    [ -r "$WSA_SYSTEM/$f" ] || { echo "reference system lacks $f" >&2; exit 1; }
done

DST="$TREE/device/microsoft/wsa-houdini"
P="$DST/proprietary/system_ext"
rm -rf "${DST:?}"
mkdir -p "$P/bin" "$P/lib64/arm64" "$P/lib/arm"
cp "$WSA_SYSTEM/bin/houdini" "$WSA_SYSTEM/bin/houdini64" "$P/bin/"
cp "$WSA_VENDOR/lib64/libhoudini.so" "$P/lib64/"
cp "$WSA_VENDOR/lib/libhoudini.so" "$P/lib/"
cp -a "$WSA_VENDOR/lib64/arm64/." "$P/lib64/arm64/"
cp -a "$WSA_VENDOR/lib/arm/." "$P/lib/arm/"

MK="$DST/houdini.mk"
{
    echo "# Generated by bin/extract-houdini-blobs.sh — do not edit by hand. ARM translation (libhoudini)"
    echo "# from the WSA reference: files in system_ext, links in system (device/microsoft/wsa_x86_64/houdini)."
    echo "PRODUCT_PACKAGES += \\"
    echo "    wsa_houdini_libhoudini \\"
    for m in lib64_libhoudini_so lib_libhoudini_so lib64_arm64 lib_arm bin_houdini bin_houdini64; do
        echo "    wsa_houdini_link_$m \\"
    done
    echo ""
    echo "PRODUCT_COPY_FILES += \\"
    (cd "$P" && find . -type f | sort | sed 's#^\./##' | grep -vxE 'lib(64)?/libhoudini\.so') | while read -r f; do
        echo "    device/microsoft/wsa-houdini/proprietary/system_ext/$f:\$(TARGET_COPY_OUT_SYSTEM_EXT)/$f \\"
    done
    echo ""
} > "$MK"
# lib{,64}/libhoudini.so — as a module, not PRODUCT_COPY_FILES. In Android 16 build/soong/fsgen turns
# PRODUCT_COPY_FILES into modules, and the lib/ directory is handed to prebuilt_renderscript_bitcode, which installs the file
# by target bitness — both libhoudini.so land in lib64/, and analysis fails with "packaging conflict at
# lib64/libhoudini.so" (30.09.2026). This is the translator's only same-named pair in lib/ and lib64/.
cat > "$DST/Android.bp" <<'BP'
// Generated by bin/extract-houdini-blobs.sh — do not edit by hand.
cc_prebuilt_library_shared {
    name: "wsa_houdini_libhoudini",
    stem: "libhoudini",
    system_ext_specific: true,
    compile_multilib: "both",
    check_elf_files: false,
    strip: {
        none: true,
    },
    arch: {
        x86: {
            srcs: ["proprietary/system_ext/lib/libhoudini.so"],
        },
        x86_64: {
            srcs: ["proprietary/system_ext/lib64/libhoudini.so"],
        },
    },
}
BP
n=$(( $(grep -c 'TARGET_COPY_OUT_SYSTEM_EXT' "$MK") + 2 ))
echo "done: $DST ($n files, $(du -sh "$DST/proprietary" | cut -f1))"
